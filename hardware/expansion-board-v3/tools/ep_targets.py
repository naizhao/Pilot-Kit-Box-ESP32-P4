#!/usr/bin/env python3
"""需要打散热/接地过孔的焊盘名单——export_dsn.py 与 thermal_vias.py 共用。

## 为什么单独成文件

两边必须用**同一份**名单，否则会出现最坏的情况：export_dsn 给 A 芯片留了内层
禁布区、thermal_vias 却去 B 芯片打孔，结果是"该留的地方被走线占了、留出来的
地方没人用"。名单一旦分叉，症状是隐性的（DRC 全绿、孔数偏少），很难发现。

## 为什么必须点名，不能自动识别

thermal_vias 第一版按"大的 GND 焊盘"自动筛，把排针 J1、四个 U.FL 座、电容、
开关、USB-C 屏蔽全算成了 EP，最危险的是 **ANT1（IFA 天线）也进了名单、
准备打 16 个过孔**——天线上打孔直接毁掉辐射特性。
"看着像就当成是"这类自动识别，在硬件上代价太高。

名单来源：QFN/DFN 带散热焊盘的芯片 + LAYOUT_CONSTRAINTS §2.4 点名的 SAW 地焊盘。
"""

TARGETS = {
    "U8":  "RP2040 QFN-56 EP",
    "U10": "CC1312R QFN-48 EP",
    "U11": "QPL9547 DFN-8 EP（1090 LNA①，射频地）",
    "U13": "AD8319 LFCSP-8 EP（检波器，射频地）",
    "FL1": "TA0970A SAW① 长地焊盘（§2.4 要求 ≥3 个）",
    "FL2": "TA0970A SAW② 长地焊盘（§2.4 要求 ≥3 个）",
}

# 判定一个焊盘是不是 EP：GND 网络、在 F.Cu、且长边 >1.4mm（普通引脚都比这窄）
EP_MIN_SIDE_MM = 1.4

# ── 孔阵规格 ──────────────────────────────────────────────────────────
# 第一版按 0.8mm 间距在整个 EP 里铺满，U10 打了 **33 个**。评审问"需要这么大
# 面积吗"，一查业界通行做法：QFN 的 EP 用 **9–25 个** Ø0.3–0.33mm 孔、
# **1.0–1.2mm 间距**（Microchip AN4498 / Infineon AN72845 / TI SLOA122 口径一致）。
# 33 个、0.8mm 间距是孔数超上限、间距也比推荐密。
#
# 而热需求这边：CC1312R 发射态约 82mW、RP2040 满载约 100mW——这个量级下
# 16 个孔和 33 个孔的热阻差别没有工程意义。孔数不是越多越好，密排还会在回流焊
# 时抢锡、加大空洞率。
PITCH_MM = 1.2                   # 孔心间距，取推荐区间上限（省面积）

# 目标孔数。keepout 面积按这个阵列反算，不再按整个 EP 铺——省下的是 EP 四周的
# 环带，正好是内层走线最想穿的地方。走线在 In2 从 EP 下方过不影响电气：
# 叠层 F/In1(GND)/In2/In3/In4(GND)/B，EP 与 In2 之间隔着 In1 整块地平面。
EP_VIAS = {
    "U8":  9,      # 3×3，RP2040 3.20mm EP
    "U10": 16,     # 4×4，CC1312R 5.15mm EP
}
# 没列的（U11/U13/FL1/FL2）EP 本身就只有 1-2mm²，整块禁布也不占地方，维持原样。
