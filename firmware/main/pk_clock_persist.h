/*
 * pk_clock_persist — 把系统时间低频写进 NVS，开机再读回来当兜底。
 *
 * 它解决的是一件很窄的事：**开机后、任何授时来源就位之前，别让时钟停在 1970**。
 *
 * 恢复出来的时间**必然偏早**，而且偏多少无从知道——关机期间时钟照常流逝，
 * 但设备没通电、数不出来。所以它在 pk_clock 的可信度阶梯里排最低档("nvs")，
 * GPS/蓝牙/GNSS 模块 RTC 任何一个就位都会立刻把它顶掉（见 pk_clock.h）。
 *
 * 它不是 RTC，也不打算假装是。真正的「开机即有准确时间」要靠给 GNSS 模块的
 * VBAT 脚一路常供电（模块内部自带 RTC，手册 §2.4），那是硬件改动；在那之前
 * 和之后，这个兜底都有价值——纽扣电池没插、主电池彻底放空时它是最后一道。
 */

/* 开机调用一次：先从 NVS 读回上次保存的时刻喂给 pk_clock（source="nvs"），
 * 再起一个低频任务周期性把当前时间写回去。
 *
 * 调用时机：必须在 nvs_flash_init() 之后、各授时来源（GPS/BLE）启动之前。
 * 晚于授时来源也不会写错时间（阶梯会挡住），但那样开机最初几秒仍是 1970，
 * 兜底的意义正好丢在那几秒里。 */
void pk_clock_persist_start(void);
