/*
 * config_diaglog.h — 诊断记录的总开关（写不写 SD 卡）。
 *
 * ── 为什么必须有这个开关 ────────────────────────────────────────────
 * 诊断记录会往用户自己的 SD 卡上持续写文件，内容里还带**位置坐标**
 * （射频问题极度依赖"在哪测的"，所以 rf1090.csv 记了 lat/lon）。一个开机
 * 就默默写、用户既不知情也关不掉的记录器，无论出发点多好，性质上就是背后
 * 收集数据。
 *
 * 所以三条都要有，缺一不可：
 *   1. **默认关闭** —— 不是"默认开启但可以关"。用户没要求过记录，就不该记；
 *   2. **界面里看得见、能关** —— 开关放在 1090 高级页（调试功能的归属地），
 *      不藏在菜单深处；
 *   3. **能删干净** —— 关闭时直接删除已写的文件，不留"关了但数据还在卡上"
 *      这种状态。另有独立的"清除"动作供随时使用。
 *
 * 另外记录本身还带容量上限与自清理（见 rf1090_log.h）：即使用户开着不管，
 * 它也不会把卡写满、不会无限累积历史轨迹。
 *
 * 这个开关是**全局**的：以后再加任何往卡上写诊断数据的模块，都必须先问它，
 * 不要各自再造一个各自为政的小开关——用户只该有一个地方能关掉全部。
 */
#pragma once

#include <stdbool.h>

/* 默认 false（关闭）。开机从 NVS 读。 */
bool pk_diaglog_enabled(void);

/* 打开/关闭。**关闭时会删除已记录的文件**——"关了但数据还留在卡上"是最糟的
 * 状态：用户以为清掉了，其实没有。 */
void pk_diaglog_set(bool on);

/* 立刻清除已记录的诊断文件（不改开关状态）。 */
void pk_diaglog_clear_files(void);

/* 已记录文件的总字节数，供界面显示"现在占了多少"。无卡或无文件时返回 0。 */
long pk_diaglog_size_bytes(void);

void pk_config_diaglog_load(void);
