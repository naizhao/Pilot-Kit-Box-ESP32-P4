/*
 * pk_syslog.h — 把 P4 自己的全部 ESP_LOG 输出也落到 SD 卡。
 *
 * ── 为什么需要它 ────────────────────────────────────────────────────
 * rf1090_log 只解决了半个问题：它记的是 RP2040 经 UART 送过来的 1090 统计。
 * 而 P4 自己产生的日志——GPS 定位与可见星、IMU/磁力计、气压高度、SY6970
 * 电源、aero 数据库、UI 状态、每一条 warning 和 error——仍然只写串口。
 * P4 那根线一拔，这些全部丢失，跟当初 RP2040 的处境一模一样。
 *
 * 排查射频问题时恰恰需要它们：帧数掉下去的那一刻，是不是同时在充电？是不是
 * 刚进了隧道（GPS 星数骤降）？是不是屏幕在刷新？只有把两边的时间线对起来
 * 才看得出关联。
 *
 * ── 怎么做 ──────────────────────────────────────────────────────────
 * 用 esp_log_set_vprintf() 挂钩，日志**照常**送串口（行为不变），同时复制一份
 * 进环形缓冲；由一个低优先级后台任务批量写盘。
 *
 * 钩子里绝不碰文件：ESP_LOG 可能在任何任务、任何时刻被调用，在里面做 fopen/
 * fwrite 会让调用方阻塞在 FATFS 上——那意味着一条日志能拖慢 1090 收帧。
 * 环形缓冲满了就丢**新**的并计数：丢新的比丢旧的好，因为写满往往意味着正在
 * 刷屏，而刷屏的头几条才是有信息量的。
 *
 * ── 隐私与容量 ──────────────────────────────────────────────────────
 * 受 config_diaglog 的总开关控制，**默认关闭**；关掉时文件会被删除。
 * 文件有容量上限并自动轮转，开着不管也不会写满卡。详见 config_diaglog.h。
 */
#pragma once

/* 注册日志钩子并启动写盘任务（幂等）。应尽早调用——在它之前产生的日志只会
 * 进串口，落不了盘。 */
void pk_syslog_init(void);

/* 当前缓冲溢出丢弃的日志条数（诊断用：非 0 说明写盘跟不上产生速度）。 */
unsigned pk_syslog_dropped(void);
