/*
 * rf1090_log.h — 1090 接收链诊断长期记录到 SD 卡（CSV）。
 *
 * ── 为什么需要它 ────────────────────────────────────────────────────
 * 1090 的关键统计（preamble 命中、解出帧数、噪声边沿、捕获层丢沿）全部产生
 * 在 **RP2040** 上，经 UART 的 HEALTH_STATS 每秒送到 P4。P4 此前只是把它
 * `ESP_LOGI` 到串口——于是这些数据的存活完全取决于**当时有没有插着 USB 线**：
 *
 *   · RP2040 那根 USB 没插 → 它自己的 CDC 读不到；
 *   · P4 那根 USB 没插     → 串口日志没人接，整段丢掉；
 *   · 两根都插着，但中途拔线焊板/关机 → 那一段是空的。
 *
 * 而射频调试恰恰全程在拔线、上烙铁、换天线、装壳——"要数据就得一直插着线"
 * 这个前提本身就不成立。2026-09-14 就因此丢了整轮外场数据，只能靠回忆复述
 * 现象，还把外置天线的读数当成了板载的分析。
 *
 * 所以把记录搬到设备自己身上：**两根 USB 都不插也照常记**，回头插卡或插线读。
 * 这与 power_log.c 是同一个理由的同一个解法（那边是"拔掉 H1 就没串口，也就
 * 测不了放电"），实现也刻意保持一致。
 *
 * ── 记什么 ──────────────────────────────────────────────────────────
 * 每行一条，**计数与产生它的配置写在同一行**：天线选择、门限、以及本周期内
 * pre/f56/f112/noise/ovr 的**增量**。配置和计数分开记是上一版的错误——事后
 * 根本无法判断某段数据是哪一路天线、哪个门限下测的。
 *
 * 增量而不是累计值：累计值要靠读的人自己做差分，而中途重启会让累计归零、
 * 差分变成一个巨大的负数。增量直接就是"这 10 秒收了几帧"。
 *
 * 附带 GPS 位置与可见星数：射频问题极度依赖"在哪测的、周围什么环境"，
 * 事后回看一串没有地点的帧数说明不了任何问题。
 *
 * ── 写入策略 ────────────────────────────────────────────────────────
 * 10 s 一行（比 power_log 的 60 s 密，射频调试需要更细的粒度，一轮门限扫描
 * 每点才 10 s）。每行 fflush + fsync：FATFS 上只 fflush 不 fsync，目录项里
 * 的文件大小不更新，掉电丢整段而且平时完全看不出来。
 *
 * 无卡时静默待命并持续重试——排障时经常是先开机后插卡。
 */
#pragma once

/* 启动记录任务（幂等）。SD 未挂载时自动待命，插卡后开始写。 */
void rf1090_log_init(void);

/* 把已有的 /sdcard/rf1090.csv 整个吐到串口日志里。
 * 给"设备刚拔回来、插上线想看看这段时间发生了什么"用，省去拆卡。 */
void rf1090_log_dump(void);
