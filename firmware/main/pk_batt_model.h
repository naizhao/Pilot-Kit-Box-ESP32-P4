/*
 * pk_batt_model.h — 电芯 SoC 模型（端电压 → 剩余电量百分比）。
 *
 * 为什么单独一个文件：这条曲线是**电芯的化学属性**，跟哪一颗充电芯片在
 * 采样毫无关系。它原先长在 power_eta6098.c 里——那是 2026-08 第一个
 * backend 落地时的历史位置，当时只有一个消费方所以没人觉得别扭。等
 * SY6970 backend 上来之后，v4 板上的电量要跨文件去 include 一颗**板上
 * 根本不存在的充电芯片**的头文件才能算出来（微雪载板的 ETA6098 自
 * 2026-09-10 起已不再注册，见 main.c 的电源链注释）。
 *
 * 搬出来之后，power_eta6098.c 只剩 ADC 采集这一件它真正该管的事。
 *
 * ── 模型口径：本机实测标定（2026-09-13）────────────────────────────
 * 分段线性，7 段，拐点 4026 / 3872 / 3700 / 3583 / 3380 / 3249 / 2839 mV。**这些数不是查手册或抄通用曲线来的，是这台设备自己跑出来的。**
 *
 * 标定方法：满电（term_done）后拔掉外部供电，设备以正常工作负载连续放电
 * 到自动关机，全程由 power_log 每 60 s 记一行到 SD 卡。原始记录是 502 点、
 * 8.37 小时；剔除开头约 7 分钟 H1 仍供电、电池空载的 7 点后，真正用于拟合
 * 的是 495 个有效放电点、8.25 小时、4044 → 2724 mV（若把空载 4164 mV
 * 混进去，会把曲线的 100% 点抬高约 120 mV）。电压先做 15 点滑动平均去
 * 20 mV 量化噪声，SoC 按时间线性反推（恒流近似），
 * 再对量化噪声做单调化，最后选 7 个拐点拟合。
 *   电池：标称 5000 mAh 软包
 *   平均放电电流：5000 mAh ÷ 8.25 h ≈ 606 mA（满负载：屏亮 + ADS-B + 传感器）
 *
 * ── 关键：这是**带负载**的运行曲线，不是静置开路曲线 ────────────────
 * 旧版是从 power_eta6098.c 搬来的通用锂电曲线，按静置开路电压标定。用在
 * 运行中的读数上系统性虚低——实测最大误差 42%、平均 24%：真实 50% 时它
 * 报 18%，真实 80% 时它报 50%。原因是 606 mA 负载在电池内阻上压掉约
 * 120 mV，而查表并不知道这件事。
 * 新曲线直接用带负载的实测电压建立映射，**把 606 mA 那一档的压降包进
 * 曲线本身**。别的工况（尤其充电）要先折算回这个口径再查表——折算式与
 * 两个方向的内阻见下面的"负载模型"。
 * 同口径复核：新曲线最大误差 8%、平均 2.5%。
 *
 * ── 已知限制 ────────────────────────────────────────────────────────
 * 1. 曲线绑定历史标定时的"满负载 ~606 mA"工况。2026-09-29 的简易台架
 *    测得当前稳定电池侧电流约 750 mA，但这不是一轮完整放电标定，不能据此
 *    改曲线或 R_DIS。**放电电流在本硬件上测不到**
 *    （SY6970 的 ICHGR 只测充电方向，[DS] p.24-25），所以放电侧只能按
 *    这一个标称负载折算。背光调暗或关掉 SDR 时实际压降变小，真实电量会
 *    比显示的**更多**。这是电压法在本板的天花板，要再进一步得上库仑计。
 * 2. 标定时发现平滑后的电压序列**仍不单调**（75% 处比 80% 还高）。电压
 *    回升只能来自负载变小，说明"时间线性 = SoC 线性"的恒流假设并不严格
 *    成立，用它反推的 SoC 自带误差。同一个根因：没有电流测量就分不清
 *    "电量掉了"和"负载重了"。
 * 3. 换电芯要重标。重跑一遍上面的标定方法即可，数据已经能自动落卡。
 *
 * 纯函数、无状态、无 IDF 依赖，host 单测直编（test_pk_batt_model.c）。
 */
#pragma once

#include <stdbool.h>

/* ── 负载模型：把任意工况折算回本曲线的口径 ─────────────────────────
 *
 * 曲线是在"满负载放电 ~606 mA"这一个工况下测的，所以任何**别的**工况都
 * 得先折算成等效的"606 mA 放电电压"再查表。这里必须区分电源来源：
 *   已确认无外部电源：BATV 已经是带载端电压，原样查表；
 *   已检测到外部电源、未充电：BATV 近似开路电压，减 LOAD_NOM×R_DIS；
 *   已检测到外部电源且充电：再减 ICHG×R_CHG，去掉充电极化抬升。
 * 旧实现不分来源，一律再减 LOAD_NOM×R_DIS，等于仅电池时重复扣除约
 * 121mV。这会放大供电切换时的显示跳变，但不是 H1 场景的完整根因：载板
 * H1 的 USB0_5V 经主板 Q2 从 U19 下游给系统供电，U19 在 H1 插入和拔出后
 * 都报告 VBUS=0，当前 P4 也没有 H1 VBUS 在位信号。因此当前调用方传入的
 * 状态只是“U19 已检测到外部电源”，不能识别 H1；VCC_5V 在电池升压运行时
 * 也存在，不能单独拿它当 H1 在位信号。详见 power_log.h 和
 * docs/internal/2026-09-29-battery-percent-jump-root-cause.md。
 *
 * ── 为什么是两个 R ─────────────────────────────────────────────────
 * 充放电方向的等效内阻**不相等**，这是 2026-09-13 实测撞出来的，不是
 * 从教科书抄的：
 *   R_DIS：拔掉外部供电那一瞬间，负载从 0 跳到满载，电压跳降 120 mV
 *          （4164→4044，t=360s→420s 那两行）→ 120mV / 597mA ≈ 201 mΩ
 *   R_CHG：2050 mA 充电中 BATT=4184 mV，拔掉 9V 后满载为 3624 mV。
 *          560mV 总跳变中已有 120mV 是负载压降，充电方向只有 440mV：
 *          (560−120)mV / 2050mA ≈ 214 mΩ
 * 差异来自充放电极化的不对称（欧姆分量相同，浓差/活化过电位不同）。
 * 两条路径因此折回同一个带载电压：
 *     充电中 4184 − 2050×0.214 − 606×0.201 ≈ 3625 mV
 *     拔电后 3624（已经带载，不再重复扣压降）       = 3624 mV
 *
 * 已知薄弱点：R_CHG 只有 2050 mA 这**一个**数据点，其它电流下未必线性
 * （极化随电流非线性）。CV 末期小电流时补偿量小，误差影响也小；真要更准
 * 得在几个电流档各测一次跳降。
 */
#define PK_BATT_R_CHG_MOHM   214   /* 充电方向，实测 (560−120)mV/2050mA */
#define PK_BATT_R_DIS_MOHM   201   /* 放电方向，实测 120mV/597mA  */
#define PK_BATT_LOAD_NOM_MA  606   /* 曲线标定时的平均负载（5000mAh/8.25h）*/

/*
 * 端电压（mV）→ 电量百分比。返回值恒在 0..100（越界输入按上下饱和钳死，
 * 负输入也返回 0——ADC/解码出错时不许算出负数或大数喂给 uint8_t 字段）。
 * 对电压单调不减：电量在充电过程中不会往回跳。
 */
int pk_batt_mv_to_pct(int batt_mv);

/*
 * 把当前端电压折算到上述带载曲线口径。external_power_detected 必须表示调用方
 * **实际能检测到**的外部供电；当前 SY6970 调用方只能检测 U19 BUS，不能检测
 * 绕过 U19 的载板 H1。ICHGR 仅在 charging=true 时有效；非充电状态即使寄存器
 * 保留旧值也会被忽略。返回 mV，不做 SoC 钳位。
 */
int pk_batt_equiv_loaded_mv(int batt_mv, bool external_power_detected,
                            bool charging, int ichg_ma);
