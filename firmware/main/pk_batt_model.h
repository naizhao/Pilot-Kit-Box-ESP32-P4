/*
 * pk_batt_model.h — 电芯 SoC 模型（端电压 → 剩余电量百分比）。
 *
 * 为什么单独一个文件：这条曲线是**电芯的化学属性**，跟哪一颗充电芯片在
 * 采样毫无关系。它原先长在 power_eta6098.c 里——那是 2026-08 第一个
 * backend 落地时的历史位置，当时只有一个消费方所以没人觉得别扭。等
 * SY6970 backend 上来之后，v4 板上的电量要跨文件去 include 一颗**板上
 * 根本不存在的充电芯片**的头文件才能算出来（微雪载板的 ETA6098 自
 * 2026-09-10 起已不再注册，见 main.c 的电源链注释）。
 *
 * 搬出来之后，power_eta6098.c 只剩 ADC 采集这一件它真正该管的事。
 *
 * ── 模型口径：本机实测标定（2026-09-13）────────────────────────────
 * 分段线性，7 段，拐点 4164 / 3844 / 3704 / 3544 / 3384 / 3244 / 3224 /
 * 2724 mV。**这些数不是查手册或抄通用曲线来的，是这台设备自己跑出来的。**
 *
 * 标定方法：满电（term_done）后拔掉外部供电，设备以正常工作负载连续放电
 * 到自动关机，全程由 power_log 每 60 s 记一行到 SD 卡。得到 502 个采样点、
 * 8.37 小时、4164 → 2724 mV 的完整量程。SoC 按时间线性反推（恒流近似），
 * 再对量化噪声做单调化，最后选 7 个拐点拟合。
 *   电池：标称 5000 mAh 软包
 *   平均放电电流：5000 mAh ÷ 8.37 h ≈ 597 mA（满负载：屏亮 + ADS-B + 传感器）
 *
 * ── 关键：这是**带负载**的运行曲线，不是静置开路曲线 ────────────────
 * 旧版是从 power_eta6098.c 搬来的通用锂电曲线，按静置开路电压标定。用在
 * 运行中的读数上系统性虚低——实测最大误差 42%、平均 24%：真实 50% 时它
 * 报 18%，真实 80% 时它报 50%。原因是 597 mA 负载在电池内阻上压掉约
 * 200 mV，而查表并不知道这件事。
 * 新曲线直接用带负载的实测电压建立映射，**把压降包进曲线本身**，因此
 * 不需要任何 I×R 补偿——那条路走不通，放电电流在本硬件上根本测不到
 * （SY6970 的 ICHGR 只测充电方向）。
 * 同口径复核：新曲线最大误差 8%、平均 2.3%。
 *
 * ── 已知限制 ────────────────────────────────────────────────────────
 * 1. 曲线绑定"满负载 ~597 mA"这一个工况。负载显著变化（背光调暗、关掉
 *    SDR）时电压压降变小，实际电量会比显示的**更多**。要覆盖多工况得按
 *    电流分族，而放电电流测不到，所以做不了——这是电压法的天花板。
 * 2. 充电中的读数方向相反（端电压被抬高），本模块不处理，由调用方决定
 *    （见 power_sy6970.c 的 build_snapshot 注释与那里的封顶策略）。
 * 3. 换电芯要重标。重跑一遍上面的标定方法即可，数据已经能自动落卡。
 *
 * 纯函数、无状态、无 IDF 依赖，host 单测直编（test_pk_batt_model.c）。
 */
#pragma once

