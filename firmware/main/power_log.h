/*
 * power_log.h — 电池状态长期记录到 SD 卡（CSV）。
 *
 * ── 为什么需要它 ────────────────────────────────────────────────────
 * 2026-09-13 做放电标定时撞到一个死结：**要让电池真放电就必须拔掉 H1，
 * 而拔了 H1 就没有串口**。
 *
 * 根因是载板的供电拓扑（docs/hardware/board_pinout-zh_CN.md:118）：
 *   H1(USB-C) VBUS → 载板 +5V_SYS ──同一网络── J1/J3 的 VCC_5V
 *                                                  ↓
 *                                   U1/U2/U3 LDO → 3V3_* → 全部数字电路
 *                                                  ↑
 *                                SY7069(升压) ← SYS_4V ← BATFET ← 电池
 * 中间没有隔离、没有限流开关。所以只要 H1 插着电脑，VCC_5V 就被电脑顶到
 * 5 V，SY7069 停止升压，**系统全部负载改吃电脑的电，电池空载挂着**。
 * 实测：插着 H1 时电池 1.28 小时零下降（434 个采样点全落在三个相邻 ADC
 * 码上）；拔掉瞬间电压掉 122 mV（电量 100%→91%），插回立刻回弹。
 *
 * 更麻烦的是 SY6970 **看不到这件事**——外部电从 VCC_5V 进来，绕过了它的
 * BUS 脚，于是它仍然如实报 `src=BATTERY / vbus=0`。屏上显示"电池供电
 * 100%"，实际是电脑在供电、电池根本没放。这个陷阱在当前硬件上无解
 * （要判它得在 VCC_5V 上加检测），只能记在这里提醒后来者：
 * **插着 H1 测不出真实功耗，也做不了放电标定。**
 *
 * 于是把记录搬到设备自己身上：拔掉 H1 靠电池跑，数据落 SD，回头插上读。
 *
 * ── 顺带的长期价值 ──────────────────────────────────────────────────
 * 这不只是一次性的标定工具。有了它，任何电池相关的问题（掉电快、充不满、
 * 温度异常）都能翻历史曲线，不必守着串口复现。
 *
 * ── 写入策略 ────────────────────────────────────────────────────────
 * 60 s 一行，追加写 /sdcard/power.csv。每行写完 fflush + fsync：FATFS 上
 * 只 fflush 不 fsync，目录项里的文件大小不更新，掉电会丢整段、而且平时
 * 完全看不出来（教训见 pk_rec_store_fs.c:568 那段注释）。60 s 属于低频点，
 * 付得起 FAT/目录扇区的写入代价。
 *
 * 无卡时静默跳过并持续重试——排障时经常是先开机后插卡。
 */
