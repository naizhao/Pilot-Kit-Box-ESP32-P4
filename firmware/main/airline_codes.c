/*
 * airline_codes.c — ICAO 3-letter → IATA + name table.
 *
 * Data source: Wikipedia's per-letter "List of airline codes" articles
 *   (en.wikipedia.org/wiki/List_of_airline_codes_(A) … (Z)),
 * which are a community-maintained mirror of ICAO Doc 8585 "Designators
 * for Aircraft Operating Agencies". The corpus is more current than
 * the openflights / npow snapshots used in the original version of
 * this table — covers post-2020 starts (One Air, Bamboo, …) and
 * tracks rebrandings (Lufthansa-not-Deutsche-Luft-Hansa).
 *
 * Augmented with a small MANUAL_ADDITIONS table in the generator for
 * carriers Wikipedia's per-letter lists haven't yet picked up — mostly
 * post-2018 Chinese cargo / regional carriers (Jingdong / 京东 / JDL,
 * Tianjin Airlines / GCR, Urumqi / URC, etc.).
 *
 * Defunct / merged / renamed carriers are filtered at generation time
 * by scanning the Comments cell for keywords ("became", "defunct",
 * "ceased", …) — this kills the historic "Deutsche Luft Hansa" row on
 * the D page that would otherwise shadow the modern "Lufthansa" row on
 * the L page (both share ICAO=DLH).
 *
 * Sort order: ASCENDING by ICAO code. The lookup uses binary search
 * and assumes this property — keep it stable when adding entries
 * manually, or re-run the regen script.
 *
 * Regen recipe (offline, one-shot):
 *   cd firmware
 *   scripts/gen_airline_codes.py --letters all --out-block /tmp/x.c
 *   # then splice the block between the s_airlines[] braces below
 *
 * The script polls the Wikipedia API at 1 req/s with a contact UA per
 * their automated-access policy, fetching ~25 KB of wikitext per
 * letter and caching results under /tmp/pkb_airlines_cache.
 *
 * Footprint: ~5500 entries × (~12 B pointers + ~30 B strings) ≈ 230 KB
 * in .rodata (flash). Zero DRAM cost. Lookup is sub-µs with binary
 * search (~13 comparisons for 5500 entries).
 */

