/*
 * touch_gt911.h — GT911 触摸接入 LVGL。
 */
#pragma once

#include "esp_err.h"

/*
 * 探测 GT911、初始化并注册为 LVGL 指针设备。须在 lv_init() 之后、且 I²C0
 * 总线已由 imu_task 建好之后调用。
 *
 * 触摸缺席不该拖垮显示：探不到芯片时返回 ESP_ERR_NOT_FOUND 并记一条 error，
 * 调用方继续跑即可——PFD 照画，只是点不动。
 */
esp_err_t pk_touch_init(void);

/* 自愈重试的首次间隔与封顶间隔。 */
#define PK_TOUCH_RETRY_FIRST_US   (2 * 1000 * 1000)
#define PK_TOUCH_RETRY_MAX_US     (30 * 1000 * 1000)

/*
 * 触摸没初始化成功时，周期性重试。每帧调开销就是一个指针比较（成功过就立刻
 * 返回），放在渲染循环里即可。必须从**跑 LVGL 的那个任务**调用（内部可能
 * lv_indev_create()）。
 *
 * 两条触发路径：
 *
 *   ① I²C0 总线刚被救回来一轮 → 立即重试（不等退避）。
 *      2026-08-03 真机形态：总线在 GT911 初始化中途塌了，日志里只有
 *      「GT911 found」没有「GT911 ready」，姿态和高度也一起挂。
 *      背景见 pk_i2c0_recover.h。
 *
 *   ② 到点了 → 自愈重试，2/4/8/16/30 s 指数退避封顶。
 *      2026-08-04 上机后补的：现象是"偶发拉不起触摸，重启才好"。此时总线
 *      只在 GT911 初始化那一瞬间抖了一下就自己好了，baro/imu 全程正常，
 *      没有任何器件报告失败，于是总线恢复不会被触发、代数永远停在 0——
 *      只看代数的话触摸再也等不到第二次机会。
 *
 * 不设重试次数上限：4.3″ 板没有实体按键，触摸是唯一输入，拉不起来等于整机
 * 不可用，只能断电重启。宁可一直用 30 s 的间隔敲门。
 */
void pk_touch_retry_tick(void);
